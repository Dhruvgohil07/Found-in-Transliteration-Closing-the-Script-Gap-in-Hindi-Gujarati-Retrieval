"""Hindi vs Gujarati: the same methods side by side, with their rank in each language (Phase 10).

Run from the repo root inside the conda env `script-gap`, after both final tables:

    python -m scripts.compare_languages --config configs/compare_languages_hi_gu.yaml

The config pairs each method's row label in the two final tables (the labels
differ where a choice made on tune differs, e.g. top-5 vs top-3 candidates).
For every query set the script prints and writes, per method, ``metric`` and
GapRecovered in each language, and the method's rank in each language
(1 = best; tied scores share the better rank). The review-gate question "does
the Hindi method ranking hold for Gujarati?" is answered by Kendall's tau-b
between the two rankings: +1 means the same order, 0 no relation, and tau-b
counts ties correctly. With only a handful of methods tau is a description,
not a test. Every number is read from the two final-table CSVs, which trace
each cell to its run file.
"""

import argparse

import pandas as pd
from scipy.stats import kendalltau

from src.utils.config import load_config, resolve_path

SET_LABELS = {"native": "native", "roman_natural": "natural", "roman_rule": "rule"}


def ranks(scores: pd.Series) -> pd.Series:
    """Rank 1 = highest score; tied scores share the better rank."""
    return scores.rank(ascending=False, method="min").astype(int)


def rank_agreement(a: pd.Series, b: pd.Series) -> float:
    """Kendall's tau-b between two score lists over the same methods."""
    common = a.index.intersection(b.index)
    return float(kendalltau(a[common], b[common]).statistic)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", required=True)
    cfg = load_config(parser.parse_args().config)
    langs = list(cfg["tables"])                       # e.g. [hi, gu]
    metric = cfg["metric"]
    tables = {lang: pd.read_csv(resolve_path(path)) for lang, path in cfg["tables"].items()}

    lines = [
        f"# Hindi vs Gujarati ({cfg['split']} split)",
        "",
        f"Generated by `scripts/compare_languages.py --config {parser.parse_args().config}`.",
        f"{metric}, with GapRecovered in brackets (each language against its own dense e5 baselines) "
        "and the method's rank in that language (1 = best). Read from "
        + ", ".join(f"`{p}`" for p in cfg["tables"].values()) + ".",
        "Kendall's tau-b compares the two rankings: +1 = same order, 0 = unrelated.",
        "",
    ]
    latex_cells: dict[str, dict[str, str]] = {}    # method label -> {query_set/lang: cell}
    taus: dict[str, float] = {}
    for query_set in cfg["query_sets"]:
        scores, gaps = {}, {}
        for lang in langs:
            t = tables[lang][tables[lang]["query_set"] == query_set].set_index("method")
            labels = {row["label"]: row[lang] for row in cfg["rows"]}
            present = {label: m for label, m in labels.items() if m in t.index}
            scores[lang] = pd.Series({label: t.loc[m, metric] for label, m in present.items()})
            gaps[lang] = pd.Series({label: t.loc[m, "gap_recovered"] for label, m in present.items()})
        tau = rank_agreement(scores[langs[0]], scores[langs[1]])
        rank = {lang: ranks(scores[lang]) for lang in langs}

        lines += [f"## {SET_LABELS.get(query_set, query_set)} queries", ""]
        lines.append("| Method | " + " | ".join(f"{lang} {metric} | {lang} rank" for lang in langs) + " |")
        lines.append("|---|" + "---|---|" * len(langs))
        for row in cfg["rows"]:
            label = row["label"]
            if not all(label in scores[lang] for lang in langs):
                continue
            cells = []
            for lang in langs:
                gap = gaps[lang][label]
                gap_text = f" ({gap:.0%})" if pd.notna(gap) else ""
                cells += [f"{scores[lang][label]:.4f}{gap_text}", str(rank[lang][label])]
                latex_cells.setdefault(label, {})[f"{query_set}/{lang}"] = (
                    f"{scores[lang][label]:.4f} ({rank[lang][label]})")   # 4 decimals, as in the CSV: no double rounding
            lines.append(f"| {label} | " + " | ".join(cells) + " |")
        lines += ["", f"Kendall's tau-b over {len(scores[langs[0]])} methods: {tau:+.2f}", ""]
        taus[query_set] = tau
        print(f"{query_set}: tau-b {tau:+.2f}")

    out = resolve_path(cfg["output"])
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"-> {cfg['output']}")
    if "latex" in cfg:
        write_latex(cfg, langs, latex_cells, taus, parser.parse_args().config)


def write_latex(cfg: dict, langs: list[str], cells: dict, taus: dict, config_path: str) -> None:
    """One table for the report: metric (rank) per query set and language, tau-b in the last row."""
    sets = cfg["query_sets"]
    cols = [f"{s}/{lang}" for s in sets for lang in langs]
    head1 = " & ".join(f"\\multicolumn{{{len(langs)}}}{{c}}{{{SET_LABELS.get(s, s)}}}" for s in sets)
    head2 = " & ".join(lang for _ in sets for lang in langs)
    rules = " ".join(f"\\cmidrule(lr){{{2 + i * len(langs)}-{1 + (i + 1) * len(langs)}}}" for i in range(len(sets)))
    out = [
        f"% Generated by scripts/compare_languages.py --config {config_path}; never edit by hand.",
        f"\\begin{{tabular}}{{l{'r' * len(cols)}}}",
        "\\toprule",
        f"Method & {head1} \\\\",
        rules,
        f" & {head2} \\\\",
        "\\midrule",
    ]
    for label, row in cells.items():
        out.append(f"{label} & " + " & ".join(row.get(c, "--") for c in cols) + " \\\\")
    out += [
        "\\midrule",
        "Kendall's $\\tau_b$ & " + " & ".join(
            f"\\multicolumn{{{len(langs)}}}{{c}}{{{taus[s]:+.2f}}}" for s in sets) + " \\\\",
        "\\bottomrule",
        "\\end{tabular}",
    ]
    path = resolve_path(cfg["latex"])
    path.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"-> {cfg['latex']}")


if __name__ == "__main__":
    main()
