"""Per-query wins and losses of a hybrid against its two components (Phase 8 review gate).

Run from the repo root inside the conda env `script-gap`:

    python -m scripts.fusion_wins --config configs/fusion_wins_hi.yaml

Mean scores hide *where* fusion helps. For each hybrid ``{label, fused,
lexical, dense}`` (run names without the split) and each query set, using the
per-query scores on ``metric``, the table shows:

- wins / ties / losses of the hybrid against each component (a tie is an
  identical per-query score, e.g. the same top 10 in the same order);
- the queries split by which component was better on its own (lexical better,
  dense better, equal), with the mean score of each run in each bucket: does the
  hybrid follow the better component, and does it gain where both are weak?
- the queries split by length (words in the romanized query), with the mean
  gain of the hybrid over the dense component.

It is a first look; Phase 9 does the full error analysis. The Markdown file is
generated; its numbers are never typed by hand.
"""

import argparse
from datetime import date

import pandas as pd

from src.data.load import read_queries
from src.eval.evaluate import read_per_query
from src.utils.config import load_config, resolve_path


def wins_ties_losses(a: pd.Series, b: pd.Series) -> str:
    """'wins / ties / losses' of per-query scores ``a`` against ``b`` (same index)."""
    diff = a - b.loc[a.index]
    return f"{(diff > 0).sum()} / {(diff == 0).sum()} / {(diff < 0).sum()}"


def length_bucket(n_words: int, edges: list[int]) -> str:
    """Label of the length bucket for a query with ``n_words`` words, e.g. '1-3', '7+'."""
    low = 1
    for edge in edges:
        if n_words <= edge:
            return f"{low}-{edge}"
        low = edge + 1
    return f"{low}+"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", required=True)
    args = parser.parse_args()
    cfg = load_config(args.config)
    split, metric, edges = cfg["split"], cfg["metric"], cfg["length_edges"]

    def per_query(name: str) -> pd.Series:
        return read_per_query(resolve_path(cfg["per_query_dir"]) / f"{name}_{split}.csv")[metric]

    lines = [
        f"# {cfg['experiment']}: {cfg['lang']} {split} split",
        "",
        f"Generated by `scripts/fusion_wins.py --config {args.config}` on {date.today().isoformat()}.",
        "",
        f"Per-query {metric} of each hybrid against its lexical and dense component. W / T / L =",
        "queries where the hybrid scores higher / the same / lower. Buckets: queries grouped by which",
        "component was better on its own, and by query length (words in the romanized query).",
    ]
    for hybrid in cfg["hybrids"]:
        lines += ["", f"## {hybrid['label']}"]
        for qset, pattern in cfg["query_sets"].items():
            fused = per_query(hybrid["fused"].format(set=qset))
            lex = per_query(hybrid["lexical"].format(set=qset)).loc[fused.index]
            dense = per_query(hybrid["dense"].format(set=qset)).loc[fused.index]
            queries = read_queries(resolve_path(pattern.format(split=split)))
            summary = (f"Hybrid vs dense W / T / L: {wins_ties_losses(fused, dense)};  "
                       f"vs lexical: {wins_ties_losses(fused, lex)}.")
            lines += ["", f"### {qset} ({len(fused)} queries)", "", summary, "",
                      "| Queries | n | lexical | dense | hybrid | hybrid − dense | hybrid ≥ both |",
                      "|---|---|---|---|---|---|---|"]
            buckets = {
                "lexical better": lex > dense,
                "dense better": dense > lex,
                "equal (both 0)": (lex == dense) & (dense == 0),
                "equal (both > 0)": (lex == dense) & (dense > 0),
            }
            n_words = pd.Series({qid: len(queries[qid].split()) for qid in fused.index})
            for edge_label in dict.fromkeys(length_bucket(n, edges) for n in sorted(n_words)):
                buckets[f"{edge_label} words"] = n_words.map(lambda n: length_bucket(n, edges)) == edge_label
            buckets["all"] = pd.Series(True, index=fused.index)
            for label, mask in buckets.items():
                mask = mask.loc[fused.index]
                n = int(mask.sum())
                if n == 0:
                    continue
                f, l_, d = fused[mask], lex[mask], dense[mask]
                both = int(((f >= l_) & (f >= d)).sum())
                lines.append(f"| {label} | {n} | {l_.mean():.4f} | {d.mean():.4f} | {f.mean():.4f} | "
                             f"{(f - d).mean():+.4f} | {both} |")

    out = resolve_path(cfg["output"])
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
