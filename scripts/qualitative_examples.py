"""Pick qualitative examples by fixed rules and show what each method retrieved (Phase 9).

Run from the repo root inside the conda env `script-gap`:

    python -m scripts.qualitative_examples --config configs/qualitative_examples_hi.yaml

Examples are chosen by rules written before looking at them, so they are not
cherry-picked. With "gain" = per-query ``metric`` of the hybrid minus that of
the dense run (both on the natural romanized test queries):

1. the hybrid's largest gain over dense;
2. the hybrid's largest loss against dense;
3. the first query (by id) where both of the hybrid's routes score 0;
4. per failure bucket in ``buckets`` (labels from ``scripts/failure_buckets.py``):
   the query in that bucket with the largest ``rank_by`` difference
   (``a`` minus ``b``), skipping queries already chosen.

Ties are broken by query id. For each example the page shows the native,
romanized and back-transliterated query, its labels, each run's score, and
the top ``top_n`` passages of each shown run (title and the start of the
text), marked relevant (✔), judged non-relevant (✘) or unjudged (·).
The passages are found with one pass over the corpus (about a minute).
"""

import argparse
from datetime import date

import pandas as pd

from src.data.load import get_docs, read_qrels, read_queries
from src.eval.evaluate import read_per_query
from src.utils.config import load_config, resolve_path
from src.utils.runs import read_run


def top_docs(scores: dict[str, float], n: int) -> list[str]:
    """The n best docids, ties broken by docid as in our run files."""
    return [d for d, _ in sorted(scores.items(), key=lambda item: (-item[1], item[0]))[:n]]


def first_by(series: pd.Series, largest: bool, skip: set[str]) -> str:
    """Query id with the largest (or smallest) value, ties broken by id, skipping ``skip``."""
    frame = series.drop(index=list(skip & set(series.index)), errors="ignore").rename("v").reset_index()
    frame = frame.sort_values(["v", "qid"], ascending=[not largest, True])
    return frame["qid"].iloc[0]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", required=True)
    args = parser.parse_args()
    cfg = load_config(args.config)
    split, metric, n = cfg["split"], cfg["metric"], cfg["top_n"]

    def per_query(name: str) -> pd.Series:
        return read_per_query(resolve_path(cfg["per_query_dir"]) / f"{name}_{split}.csv")[metric]

    sel = cfg["select"]
    hybrid, dense, lexical = per_query(sel["hybrid"]), per_query(sel["dense"]), per_query(sel["lexical"])
    gain = hybrid - dense.loc[hybrid.index]
    labels = pd.read_csv(resolve_path(cfg["labels"]), sep="\t", dtype=str, keep_default_na=False).set_index("qid")

    # 1. Choose the examples, by the rules in the docstring
    chosen: list[tuple[str, str]] = []
    taken: set[str] = set()

    def take(qid: str, why: str) -> None:
        chosen.append((qid, why))
        taken.add(qid)

    take(first_by(gain, True, taken), "largest gain of the hybrid over dense")
    take(first_by(gain, False, taken), "largest loss of the hybrid against dense")
    both_zero = sorted(q for q in hybrid.index if lexical[q] == 0 and dense[q] == 0 and q not in taken)
    if both_zero:
        take(both_zero[0], "both routes of the hybrid score 0")
    for b in cfg["buckets"]:
        in_bucket = labels.index[labels[b["family"]] == b["value"]]
        diff = per_query(b["rank_by"]["a"]).loc[in_bucket] - per_query(b["rank_by"]["b"]).loc[in_bucket]
        take(first_by(diff, b["rank_by"].get("largest", True), taken), b["why"])

    # 2. Gather queries, runs, judgments and passages
    queries = {k: read_queries(resolve_path(p.format(split=split))) for k, p in cfg["queries"].items()}
    qrels = read_qrels(resolve_path(cfg["qrels"].format(split=split)))
    runs = {label: read_run(resolve_path(cfg["run_dir"]) / f"{name}_{split}.trec")
            for label, name in cfg["show_runs"].items()}
    scores = {label: per_query(name) for label, name in cfg["score_runs"].items()}
    wanted = {d for qid, _ in chosen for run in runs.values() for d in top_docs(run.get(qid, {}), n)}
    docs = get_docs(cfg["dataset"], wanted)

    lines = [
        f"# {cfg['experiment']}: {cfg['lang']} {split} split, natural romanized queries",
        "",
        f"Generated by `scripts/qualitative_examples.py --config {args.config}` on {date.today().isoformat()}.",
        "",
        "Examples chosen by fixed rules (see the script's docstring), not by hand. Passages: ✔ relevant,",
        "✘ judged non-relevant, · unjudged (MIRACL judges about 10 passages per query).",
    ]
    for i, (qid, why) in enumerate(chosen, start=1):
        lab = labels.loc[qid]
        lines += ["", f"## {i}. `{qid}`: {why}", "",
                  f"- native: {queries['native'][qid]}",
                  f"- romanized (natural): {queries['romanized'][qid]}",
                  f"- top-1 back-transliterated: {queries['backtranslit'][qid]}",
                  f"- labels: {lab['spelling']}; {lab['code_mixed']}"
                  + (f" ({lab['english_words']})" if lab["english_words"] else "")
                  + f"; {lab['length']}" + (f"; {lab['named_entity']}" if lab["named_entity"] else ""),
                  "- " + metric + ": " + ", ".join(f"{label} {s.loc[qid]:.3f}" for label, s in scores.items()),
                  ""]
        for label, run in runs.items():
            lines.append(f"**{label}**")
            lines.append("")
            for rank, d in enumerate(top_docs(run.get(qid, {}), n), start=1):
                rel = qrels.get(qid, {}).get(d)
                mark = "·" if rel is None else ("✔" if rel > 0 else "✘")
                doc = docs.get(d, {"title": "?", "text": ""})
                snippet = doc["text"][: cfg["snippet_chars"]].replace("\n", " ").replace("|", "/")
                lines.append(f"{rank}. {mark} {doc['title']}: {snippet}…")
            lines.append("")
    out = resolve_path(cfg["output"])
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8", newline="\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
