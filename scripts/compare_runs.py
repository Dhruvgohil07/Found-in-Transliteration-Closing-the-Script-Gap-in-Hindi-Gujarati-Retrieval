"""Compare pairs of runs on the same queries: paired t-tests with a Bonferroni correction.

Run from the repo root inside the conda env `script-gap`:

    python -m scripts.compare_runs --config configs/compare_dense_ft_native_hi.yaml

For each pair ``{label, run, baseline}`` (run names without the split) and
each metric, the table shows both means, the difference (run − baseline) and
the p-value of a paired t-test (``src.eval.significance``). Bonferroni covers
every (pair, metric) comparison in the table; * marks p < alpha / m. It answers
questions the method table does not, e.g. "did fine-tuning change *native*
performance?" (Phase 7: the catastrophic-forgetting check). The Markdown file
is generated; its numbers are never typed by hand.
"""

import argparse
from datetime import date

from src.eval.evaluate import read_per_query
from src.eval.significance import bonferroni_significant, compare
from src.utils.config import load_config, resolve_path


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", required=True)
    args = parser.parse_args()
    cfg = load_config(args.config)
    split, metrics, alpha = cfg["split"], cfg["metrics"], cfg["alpha"]

    def per_query(name: str):
        return read_per_query(resolve_path(cfg["per_query_dir"]) / f"{name}_{split}.csv")

    m = len(cfg["pairs"]) * len(metrics)
    lines = [
        f"# {cfg['experiment']}: {cfg['lang']} {split} split",
        "",
        f"Generated by `scripts/compare_runs.py --config {args.config}` on {date.today().isoformat()}.",
        "",
        f"{cfg['description']} Paired t-test per metric; Bonferroni over the table's {m} comparisons,",
        f"* means p < {alpha}/{m} = {alpha / m:.4f}.",
        "",
        "| Pair | queries | " + " | ".join(f"{x}: run / baseline (diff, p)" for x in metrics) + " |",
        "|---|---|" + "---|" * len(metrics),
    ]
    for pair in cfg["pairs"]:
        run, base = per_query(pair["run"]), per_query(pair["baseline"])
        cells = []
        for metric in metrics:
            c = compare(run, base, metric)
            star = "*" if bonferroni_significant(c.p, m, alpha) else ""
            cells.append(f"{c.mean_a:.4f} / {c.mean_b:.4f} ({c.diff:+.4f}, {c.p:.3f}{star})")
        lines.append(f"| {pair['label']} | {len(run)} | " + " | ".join(cells) + " |")

    out = resolve_path(cfg["output"])
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
