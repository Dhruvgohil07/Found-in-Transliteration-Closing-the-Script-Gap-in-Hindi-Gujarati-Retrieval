"""Build the script-gap table: native vs romanized queries, per method and metric.

Run from the repo root inside the conda env `script-gap`:

    python -m scripts.gap_table --config configs/gap_table_hi.yaml

It reads the per-query scores written by ``scripts/run_baseline.py`` and writes
a Markdown file (``output``) with, for each method:

1. the scores of every query set;
2. the relative drop of each romanized set, Delta = (M_native - M_roman) / M_native,
   with a paired t-test against native on the same queries, Bonferroni-corrected.

The file is generated; its numbers are never typed by hand.
"""

import argparse
from datetime import date

from src.eval.evaluate import read_per_query
from src.eval.gap import gap_rows
from src.utils.config import load_config, resolve_path
from src.utils.runs import run_name


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", required=True)
    args = parser.parse_args()
    cfg = load_config(args.config)
    metrics, n_sets = cfg["metrics"], len(cfg["romanized"])
    threshold = cfg["alpha"] / n_sets

    def per_query(method: str, query_set: str):
        name = run_name(cfg["lang"], method, query_set, cfg["split"])
        return read_per_query(resolve_path(cfg["per_query_dir"]) / f"{name}.csv")

    lines = [
        f"# Script gap, {cfg['lang']} {cfg['split']} split",
        "",
        f"Generated by `scripts/gap_table.py --config {args.config}` on {date.today().isoformat()}.",
        "",
        "$\\Delta = (M_{\\text{native}} - M_{\\text{roman}}) / M_{\\text{native}}$, each romanized",
        "set compared with native **on the same queries** (the human set has 50; its",
        "native column is the native score on those 50). Significance: paired t-test,",
        (f"Bonferroni over the {n_sets} romanized sets: * means p < {cfg['alpha']}/{n_sets}"
         f" = {threshold:.4f}."),
    ]
    for method, label in cfg["methods"].items():
        native = per_query(method, cfg["native"])
        romanized = {qs: per_query(method, qs) for qs in cfg["romanized"]}

        lines += ["", f"## {label}", "", "| Query set | Queries | " + " | ".join(metrics) + " |",
                  "|---|---|" + "---|" * len(metrics)]
        for query_set, scores in {cfg["native"]: native, **romanized}.items():
            values = " | ".join(f"{scores[m].mean():.4f}" for m in metrics)
            lines.append(f"| {query_set} | {len(scores)} | {values} |")

        rows = gap_rows(native, romanized, metrics, cfg["alpha"])
        lines += ["", "| Romanized set | Metric | Queries | Native | Romanized | Δ | p |",
                  "|---|---|---|---|---|---|---|"]
        for r in rows:
            star = "*" if r.significant else ""
            lines.append(f"| {r.query_set} | {r.metric} | {r.n_queries} | {r.native:.4f} | "
                         f"{r.roman:.4f} | {r.drop:.1%}{star} | {r.p:.2e} |")

    out = resolve_path(cfg["output"])
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
